-- 시퀀스 생성
CREATE SEQUENCE LS_MOTOR_RACK_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE LS_MOTOR_SUBUL_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE LS_MOTOR_ITEM_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE LS_USERS_SEQ START WITH 1 INCREMENT BY 1;

-- ============================================================
-- 0. 회원 테이블 (ls_users)
-- ============================================================
CREATE TABLE LS_USERS (
    ID NUMBER DEFAULT LS_USERS_SEQ.NEXTVAL PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(200) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(200) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    APPROVED_AT TIMESTAMP,
    APPROVED_BY NUMBER,
    CONSTRAINT CHK_USER_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT CHK_USER_ROLE CHECK (ROLE IN ('USER', 'ADMIN'))
);

-- 인덱스
CREATE INDEX IDX_USER_EMAIL ON LS_USERS(EMAIL);
CREATE INDEX IDX_USER_STATUS ON LS_USERS(STATUS);

COMMENT ON TABLE LS_USERS IS '회원 정보';
COMMENT ON COLUMN LS_USERS.ID IS '회원 ID';
COMMENT ON COLUMN LS_USERS.NAME IS '회원 이름';
COMMENT ON COLUMN LS_USERS.EMAIL IS '이메일 (로그인 ID)';
COMMENT ON COLUMN LS_USERS.PASSWORD IS '비밀번호 (해시)';
COMMENT ON COLUMN LS_USERS.STATUS IS '상태 (PENDING: 승인대기, APPROVED: 승인됨, REJECTED: 거절됨)';
COMMENT ON COLUMN LS_USERS.ROLE IS '역할 (USER: 일반, ADMIN: 관리자)';
COMMENT ON COLUMN LS_USERS.CREATED_AT IS '가입일시';
COMMENT ON COLUMN LS_USERS.APPROVED_AT IS '승인일시';
COMMENT ON COLUMN LS_USERS.APPROVED_BY IS '승인자 ID';

