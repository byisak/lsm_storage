-- ============================================================
-- 1. 재고 마스터 테이블 (ls_motor_rack)
-- ============================================================
CREATE TABLE LS_MOTOR_RACK (
    ID NUMBER DEFAULT LS_MOTOR_RACK_SEQ.NEXTVAL PRIMARY KEY,
    STORAGE VARCHAR2(50) NOT NULL,
    LOCATION VARCHAR2(50) NOT NULL,
    ITEM_CODE VARCHAR2(100) NOT NULL,
    ITEM_NAME VARCHAR2(200) NOT NULL,
    NOW_QTY NUMBER DEFAULT 0 NOT NULL,
    IN_DAY TIMESTAMP,
    REMARK VARCHAR2(500)
);

-- 인덱스
CREATE INDEX IDX_RACK_STORAGE ON LS_MOTOR_RACK(STORAGE);
CREATE INDEX IDX_RACK_LOCATION ON LS_MOTOR_RACK(LOCATION);
CREATE INDEX IDX_RACK_ITEM_CODE ON LS_MOTOR_RACK(ITEM_CODE);
CREATE INDEX IDX_RACK_ITEM_NAME ON LS_MOTOR_RACK(ITEM_NAME);

COMMENT ON TABLE LS_MOTOR_RACK IS '재고 마스터';
COMMENT ON COLUMN LS_MOTOR_RACK.ID IS '재고 ID';
COMMENT ON COLUMN LS_MOTOR_RACK.STORAGE IS '창고 번호';
COMMENT ON COLUMN LS_MOTOR_RACK.LOCATION IS '위치 (예: A-01-01)';
COMMENT ON COLUMN LS_MOTOR_RACK.ITEM_CODE IS '품목 코드';
COMMENT ON COLUMN LS_MOTOR_RACK.ITEM_NAME IS '품목명';
COMMENT ON COLUMN LS_MOTOR_RACK.NOW_QTY IS '현재 수량';
COMMENT ON COLUMN LS_MOTOR_RACK.IN_DAY IS '입고일';
COMMENT ON COLUMN LS_MOTOR_RACK.REMARK IS '비고';

-- ============================================================
-- 2. 수불 이력 테이블 (ls_motor_subul)
-- ============================================================
CREATE TABLE LS_MOTOR_SUBUL (
    ID NUMBER DEFAULT LS_MOTOR_SUBUL_SEQ.NEXTVAL PRIMARY KEY,
    STORAGE VARCHAR2(50) NOT NULL,
    LOCATION VARCHAR2(50) NOT NULL,
    ITEM_CODE VARCHAR2(100) NOT NULL,
    ITEM_NAME VARCHAR2(200) NOT NULL,
    QTY NUMBER DEFAULT 0 NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    SUBUL_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    REMARK VARCHAR2(500),
    USER_ID VARCHAR2(100) DEFAULT 'system' NOT NULL
);

-- 인덱스
CREATE INDEX IDX_SUBUL_STORAGE ON LS_MOTOR_SUBUL(STORAGE);
CREATE INDEX IDX_SUBUL_LOCATION ON LS_MOTOR_SUBUL(LOCATION);
CREATE INDEX IDX_SUBUL_ITEM_CODE ON LS_MOTOR_SUBUL(ITEM_CODE);
CREATE INDEX IDX_SUBUL_CATEGORY ON LS_MOTOR_SUBUL(CATEGORY);
CREATE INDEX IDX_SUBUL_TIME ON LS_MOTOR_SUBUL(SUBUL_TIME DESC);

COMMENT ON TABLE LS_MOTOR_SUBUL IS '수불 이력';
COMMENT ON COLUMN LS_MOTOR_SUBUL.ID IS '이력 ID';
COMMENT ON COLUMN LS_MOTOR_SUBUL.STORAGE IS '창고 번호';
COMMENT ON COLUMN LS_MOTOR_SUBUL.LOCATION IS '위치';
COMMENT ON COLUMN LS_MOTOR_SUBUL.ITEM_CODE IS '품목 코드';
COMMENT ON COLUMN LS_MOTOR_SUBUL.ITEM_NAME IS '품목명';
COMMENT ON COLUMN LS_MOTOR_SUBUL.QTY IS '거래 수량';
COMMENT ON COLUMN LS_MOTOR_SUBUL.CATEGORY IS '거래 분류 (입고/출고/이동(출)/이동(입)/수정)';
COMMENT ON COLUMN LS_MOTOR_SUBUL.SUBUL_TIME IS '거래 시간';
COMMENT ON COLUMN LS_MOTOR_SUBUL.REMARK IS '비고';
COMMENT ON COLUMN LS_MOTOR_SUBUL.USER_ID IS '처리자';

-- ============================================================
-- 3. 품목 마스터 테이블 (ls_motor_item)
-- ============================================================
CREATE TABLE LS_MOTOR_ITEM (
    IDX NUMBER DEFAULT LS_MOTOR_ITEM_SEQ.NEXTVAL PRIMARY KEY,
    STORAGE VARCHAR2(50) NOT NULL,
    ITEM_CODE VARCHAR2(100) NOT NULL,
    ITEM_NAME VARCHAR2(200) NOT NULL,
    ERP_RESERVATION NUMBER DEFAULT 0,
    ERP_INVENTORY10 NUMBER DEFAULT 0,
    ERP_INVENTORY11 NUMBER DEFAULT 0,
    SHORTAGE NUMBER DEFAULT 0
);

-- 인덱스
CREATE INDEX IDX_ITEM_STORAGE ON LS_MOTOR_ITEM(STORAGE);
CREATE INDEX IDX_ITEM_CODE ON LS_MOTOR_ITEM(ITEM_CODE);
CREATE INDEX IDX_ITEM_NAME ON LS_MOTOR_ITEM(ITEM_NAME);

COMMENT ON TABLE LS_MOTOR_ITEM IS '품목 마스터';
COMMENT ON COLUMN LS_MOTOR_ITEM.IDX IS '품목 IDX';
COMMENT ON COLUMN LS_MOTOR_ITEM.STORAGE IS '기본 창고';
COMMENT ON COLUMN LS_MOTOR_ITEM.ITEM_CODE IS '품목 코드';
COMMENT ON COLUMN LS_MOTOR_ITEM.ITEM_NAME IS '품목명';
COMMENT ON COLUMN LS_MOTOR_ITEM.ERP_RESERVATION IS 'ERP 예약 수량';
COMMENT ON COLUMN LS_MOTOR_ITEM.ERP_INVENTORY10 IS 'ERP 재고 (창고10)';
COMMENT ON COLUMN LS_MOTOR_ITEM.ERP_INVENTORY11 IS 'ERP 재고 (창고11)';
COMMENT ON COLUMN LS_MOTOR_ITEM.SHORTAGE IS '부족 수량';

