-- 감사 로그 시퀀스
CREATE SEQUENCE AUDIT_LOG_SEQ START WITH 1 INCREMENT BY 1;

-- 감사 로그 테이블
CREATE TABLE AUDIT_LOG (
    ID NUMBER PRIMARY KEY,
    COMPANY_ID VARCHAR2(20),
    USER_ID NUMBER,
    USER_NAME VARCHAR2(100),
    USER_EMAIL VARCHAR2(200),
    ACTION VARCHAR2(50) NOT NULL,
    RESOURCE_TYPE VARCHAR2(50) NOT NULL,
    RESOURCE_ID VARCHAR2(100),
    DESCRIPTION VARCHAR2(1000),
    IP_ADDRESS VARCHAR2(50),
    USER_AGENT VARCHAR2(500),
    OLD_VALUES CLOB,
    NEW_VALUES CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_AUDIT_ACTION CHECK (ACTION IN (
        'LOGIN', 'LOGOUT', 'LOGIN_FAILED',
        'CREATE', 'UPDATE', 'DELETE',
        'APPROVE', 'REJECT',
        'IMPORT', 'EXPORT',
        'SETTINGS_CHANGE', 'ROLE_CHANGE',
        'PASSWORD_CHANGE', 'PASSWORD_RESET'
    )),
    CONSTRAINT CHK_AUDIT_RESOURCE CHECK (RESOURCE_TYPE IN (
        'USER', 'COMPANY', 'WAREHOUSE',
        'RACK', 'ITEM', 'TRANSACTION',
        'SETTINGS', 'SYSTEM'
    ))
);

-- 인덱스
CREATE INDEX IDX_AUDIT_COMPANY ON AUDIT_LOG(COMPANY_ID);
CREATE INDEX IDX_AUDIT_USER ON AUDIT_LOG(USER_ID);
CREATE INDEX IDX_AUDIT_ACTION ON AUDIT_LOG(ACTION);
CREATE INDEX IDX_AUDIT_RESOURCE ON AUDIT_LOG(RESOURCE_TYPE, RESOURCE_ID);
CREATE INDEX IDX_AUDIT_TIME ON AUDIT_LOG(CREATED_AT DESC);
CREATE INDEX IDX_AUDIT_COMPANY_TIME ON AUDIT_LOG(COMPANY_ID, CREATED_AT DESC);

-- 코멘트
COMMENT ON TABLE AUDIT_LOG IS '시스템 감사 로그';
COMMENT ON COLUMN AUDIT_LOG.ID IS '로그 ID';
COMMENT ON COLUMN AUDIT_LOG.COMPANY_ID IS '회사 ID';
COMMENT ON COLUMN AUDIT_LOG.USER_ID IS '사용자 ID';
COMMENT ON COLUMN AUDIT_LOG.USER_NAME IS '사용자 이름 (변경 불변 기록용)';
COMMENT ON COLUMN AUDIT_LOG.USER_EMAIL IS '사용자 이메일 (변경 불변 기록용)';
COMMENT ON COLUMN AUDIT_LOG.ACTION IS '액션 종류';
COMMENT ON COLUMN AUDIT_LOG.RESOURCE_TYPE IS '리소스 종류';
COMMENT ON COLUMN AUDIT_LOG.RESOURCE_ID IS '리소스 ID';
COMMENT ON COLUMN AUDIT_LOG.DESCRIPTION IS '상세 설명';
COMMENT ON COLUMN AUDIT_LOG.IP_ADDRESS IS '요청 IP 주소';
COMMENT ON COLUMN AUDIT_LOG.USER_AGENT IS '사용자 에이전트';
