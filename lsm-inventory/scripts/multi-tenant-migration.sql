COMMENT ON COLUMN API_KEYS.ID IS '키 ID';
COMMENT ON COLUMN API_KEYS.COMPANY_ID IS '회사 ID';
COMMENT ON COLUMN API_KEYS.NAME IS '키 이름 (용도 설명)';
